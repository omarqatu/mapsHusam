/** The three property layers. */
export const PROPERTY_ICON: Record<RealEstateLayerKey, LucideIcon> = {
  rent: BedDouble,
  sale: Building,
  land: LandPlot,
};

/** The icon of a service type (its own, else its group's). */
export const serviceTypeIcon = (key: string, group: keyof typeof GROUP_ICON): LucideIcon => TYPE_ICON[key] ?? GROUP_ICON[group];

/** The icon of a property kind or service type (anything unknown: the generic one). */
export function targetIconComponent(target: MapTarget | null | undefined): LucideIcon {
  if (!target) return GROUP_ICON.misc;
  if (target.kind === 'realEstate') return PROPERTY_ICON[target.layer];
  const entry = SERVICE_BY_KEY.get(target.discriminator);
  return entry ? serviceTypeIcon(entry.key, entry.group) : GROUP_ICON.misc;
}
